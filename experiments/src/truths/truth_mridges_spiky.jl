# =============================================================================
# truth_mridges_spiky.jl — Truth for ConfigMRidgesSpiky (Protocol §4.7.1)
# =============================================================================
#
# The target factorises:
#   p(θ) = p_1(θ_1) · Π_{j=2}^d  N(θ_j; 0, σ_⊥²)|_{cube}
# with `p_1` a `K × M` mixture of spike kernels (Gaussian or Student-t).
# Truth is computed analytically modulo cube truncation:
#
# • `truth.logZ` — log of the cube-restricted normalising constant of
#   the *un-normalised* `p` divided by the box-prior normalisation
#   `(2L)^d`. The convention matches the rest of the protocol
#   (cube-prior normalisation, Protocol §5.1).
# • `truth.samples` — `d × N_ref` i.i.d. draws from `p` restricted to
#   the cube. Generated by mixture-component sampling on `θ_1` and
#   truncated-Gaussian rejection on `θ_2..θ_d`.
# • `truth.modes` — `d × (K*M)` matrix of spike centres (in
#   `truth.extras[:modes]`); used by `mode_recovery`.

import QuadGK


@inline function _spike_truncated_mass(centre::Real, σ::Real, L::Real,
                                          kernel::Symbol, ν::Real)
    if kernel == :gaussian
        d = Normal(centre, σ)
        return cdf(d, L) - cdf(d, -L)
    else  # :studentt3
        # X = centre + σ * T where T ~ TDist(ν); P(-L ≤ X ≤ L) =
        # P(-(L+centre)/σ ≤ T ≤ (L-centre)/σ).
        d = TDist(ν)
        z_hi = (L - centre) / σ
        z_lo = (-L - centre) / σ
        return cdf(d, z_hi) - cdf(d, z_lo)
    end
end

@inline function _gaussian_perp_mass(σ_perp::Real, L::Real)
    d = Normal(0.0, σ_perp)
    return cdf(d, L) - cdf(d, -L)
end


"""
    compute_truth_mridges_spiky(cfg; N_ref, seed) -> TruthSet
"""
function compute_truth_mridges_spiky(cfg::ConfigMRidgesSpiky;
                                       N_ref::Integer = 1_000_000,
                                       seed::Integer = 20260501)
    d = cfg.d
    L = cfg.L
    centres = mridges_spiky_modes_theta1(cfg)
    Kmod = length(centres)

    # 1) Normalising constant of the cube-restricted target.
    # The un-normalised log-density is built so that the marginal
    # `p_1(θ_1)` already integrates to 1 *over the real line* if
    # truncation were ignored. Truncation costs `m_k` (per-spike mass)
    # along `θ_1`, and `m_⊥` per perpendicular axis.
    masses = [_spike_truncated_mass(c, cfg.σ_spike, L, cfg.kernel, cfg.ν)
              for c in centres]
    m_perp = _gaussian_perp_mass(cfg.σ_perp, L)
    cube_mass = mean(masses) * (m_perp ^ (d - 1))   # already (1/Kmod) Σ
    log_int = log(cube_mass)
    # Per Protocol §5.1, `truth.logZ` is reported as
    #   logZ = log_int - d * log(2L)
    # so the cube-prior normalisation cancels the (2L)^d in IS.
    logZ = log_int - d * log(2 * L)

    # 2) i.i.d. truth samples.
    rng = MersenneTwister(seed)
    samples = _sample_mridges_spiky(cfg, N_ref, rng)

    μ, Σ = _empirical_moments(samples)
    Q = _empirical_quantiles(samples)

    # 3) `modes` for mode-recovery metric.
    modes = mridges_spiky_modes(cfg)

    extras = Dict{Symbol,Any}(
        :modes => modes,
        :spike_centres_theta1 => centres,
        :masses_per_spike => masses,
        :perp_mass => m_perp,
        :kernel => String(cfg.kernel),
    )

    return TruthSet(:mridges_spiky, d, cfg, samples, μ, Σ, Q, logZ, extras)
end


"""
    sample_truth_mridges_spiky(cfg, N; seed) -> d × N
"""
function sample_truth_mridges_spiky(cfg::ConfigMRidgesSpiky, N::Integer;
                                       seed::Integer = 20260601)
    rng = MersenneTwister(seed)
    return _sample_mridges_spiky(cfg, N, rng)
end


function _sample_mridges_spiky(cfg::ConfigMRidgesSpiky, N::Integer,
                                  rng::AbstractRNG)
    d = cfg.d
    L = cfg.L
    σ_spike = cfg.σ_spike
    σ_perp = cfg.σ_perp
    centres = mridges_spiky_modes_theta1(cfg)
    Kmod = length(centres)

    out = Matrix{Float64}(undef, d, N)
    written = 0
    # Simple rejection: pick a spike uniformly, draw θ_1 from its
    # kernel, accept iff inside cube; then i.i.d. truncated Gaussian
    # on θ_2..θ_d.
    while written < N
        k = rand(rng, 1:Kmod)
        c = centres[k]
        θ1 = if cfg.kernel == :gaussian
            c + σ_spike * randn(rng)
        else
            c + σ_spike * rand(rng, TDist(cfg.ν))
        end
        if abs(θ1) >= L
            continue
        end
        ok = true
        rest = Vector{Float64}(undef, d - 1)
        @inbounds for j in 1:(d - 1)
            attempts = 0
            x = 0.0
            while attempts < 1000
                x = σ_perp * randn(rng)
                if abs(x) < L
                    break
                end
                attempts += 1
            end
            if abs(x) >= L
                ok = false
                break
            end
            rest[j] = x
        end
        ok || continue
        written += 1
        out[1, written] = θ1
        @inbounds for j in 2:d
            out[j, written] = rest[j - 1]
        end
    end
    return out
end
