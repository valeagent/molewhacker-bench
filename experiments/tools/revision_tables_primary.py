def cell(prob, d, B, alg):
    return prim[(prim.problem == prob) & (prim.d == d) & (prim.B == B) & (prim.algorithm == alg)]


def usable(prob, d, B, alg):
    s = cell(prob, d, B, alg)
    return s[s.adm]


def cell_median(prob, d, B, alg, col, absolute=False):
    s = usable(prob, d, B, alg)
    if s.empty:
        return float("nan")
    v = s[col].abs() if absolute else s[col]
    return med(v)


def best_comparator(prob, d, B, col, mode, absolute=False, algs=COMPARATORS):
    """(algorithm, median) of the best admissible comparator; (None, nan) if none."""
    cands = []
    for a in algs:
        m = cell_median(prob, d, B, a, col, absolute)
        if np.isfinite(m):
            cands.append((a, m))
    if not cands:
        return None, float("nan")
    return (max if mode == "max" else min)(cands, key=lambda t: t[1])


def best_str(prob, d, B, col, mode, absolute=False, algs=COMPARATORS, scale=1.0, digits=3, sci_below=0.01):
    a, m = best_comparator(prob, d, B, col, mode, absolute, algs)
    if a is None:
        return "--"
    return fmt(scale * m, digits, sci_below) + " " + ALG_TEX[a]


def counts(prob, d, B, alg):
    s = cell(prob, d, B, alg)
    return int(s.adm.sum()), len(s)


# Consistency with the Julia medians file (same data, same rules).
def _check_against_julia():
    maxdev = 0.0
    for _, r in meds_jl.iterrows():
        for col, jcol, absolute in (("eta_Nlike", "eta_Nlike", False), ("W1_marginal_avg", "W1_marginal_avg", False),
                                    ("dlogZ", "abs_dlogZ", True)):
            if r.algorithm in ("mh", "nuts") and col == "dlogZ":
                continue
            m = cell_median(r.problem, int(r.d), float(r.B), r.algorithm, col, absolute)
            j = float(r[jcol])
            if np.isfinite(m) != np.isfinite(j):
                raise AssertionError(f"median availability differs for {r.problem} d={r.d} B={r.B} {r.algorithm} {col}")
            if np.isfinite(m):
                maxdev = max(maxdev, abs(m - j))
        n_e, n_t = counts(r.problem, int(r.d), float(r.B), r.algorithm)
        assert n_e == r.n_eligible and n_t == r.n_attempted, (r.problem, r.d, r.B, r.algorithm)
    assert maxdev < 1e-12, maxdev
    print(f"medians agree with primary_cell_medians.csv (max deviation {maxdev:.1e})")


_check_against_julia()

