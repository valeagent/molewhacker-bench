def fmt(x, digits=3, sci_below=0.01):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    ax = abs(x)
    if ax == 0:
        return r"\(0\)"
    if sci_below <= ax < 1000:
        return r"\(" + f"{x:.{digits}g}" + r"\)"
    m, e = f"{x:.2e}".split("e")
    m = m.rstrip("0").rstrip(".")
    return r"\(" + m + r"\times 10^{" + str(int(e)) + r"}\)"


def fmt_ch8(x):
    """Chapter-8 body style: 2-3 significant digits, {\\cdot}10^{e} below 1e-3."""
    if x is None or not np.isfinite(x):
        return "--"
    ax = abs(x)
    if ax >= 0.1:
        return f"{x:.3g}"
    if ax >= 1e-3:
        return f"{x:.2g}"
    m, e = f"{x:.1e}".split("e")
    return "$" + m + r"{\cdot}10^{" + str(int(e)) + "}$"


def fmt_ratio(r):
    if r is None or not np.isfinite(r):
        return "--"
    if r >= 10:
        return f"${r:.0f}\\times$"
    if r >= 2:
        return f"${r:.1f}\\times$"
    return f"${r:.2f}\\times$"


def med(v):
    v = np.asarray([x for x in v if x is not None and np.isfinite(x)], dtype=float)
    return float(np.median(v)) if v.size else float("nan")


def bold(t):
    """Bold a formatted entry; math-mode numbers need \\mathbf (\\textbf leaves math upright)."""
    if t.startswith(r"\(") and t.endswith(r"\)"):
        return r"\(\mathbf{" + t[2:-2] + r"}\)"
    if t.startswith("$") and t.endswith("$"):
        return r"$\mathbf{" + t[1:-1] + r"}$"
    return r"\textbf{" + t + "}"


def header(name, caption, label, colspec, head, ncols=None, tabcolsep="3pt"):
    if ncols is None:
        ncols = head.count("&") + 1
    return [f"% Auto-generated by experiments/tools/revision_tables_primary.py ({name}); do not edit by hand.",
            r"\begingroup", r"\scriptsize", r"\setlength{\tabcolsep}{" + tabcolsep + "}",
            r"\begin{longtable}{" + colspec + "}",
            r"\caption[" + caption[0] + "]{" + caption[1] + r"}\label{" + label + r"}\\",
            r"\toprule", head, r"\midrule", r"\endfirsthead",
            r"\multicolumn{" + str(ncols) + r"}{@{}l}{\tablename\ \thetable{} (continued)}\\",
            r"\toprule", head, r"\midrule", r"\endhead", r"\midrule",
            r"\multicolumn{" + str(ncols) + r"}{r@{}}{\emph{continued on next page}}\\",
            r"\endfoot", r"\bottomrule", r"\endlastfoot"]


def write_longtable(lines, fname):
    lines = lines + [r"\end{longtable}", r"\endgroup"]
    write_lines(lines, fname)


def write_lines(lines, fname):
    with open(os.path.join(TAB, fname), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", fname, len(lines), "lines")


