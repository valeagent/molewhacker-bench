#!/usr/bin/env julia
# =============================================================================
# table_master_results.jl — the master results table of thesis Appendix B:
# per-cell medians over admissible seeds for every (problem, dimension,
# budget, algorithm) cell of the grid, emitted as a LaTeX longtable to
# experiments/out/tables/master_results_table.tex. Admissibility follows
# the thesis protocol: seeds flagged RHAT-FAIL or BUDGET-VIOLATION are
# excluded; budget-infeasible cells carry no metrics.
#
# Usage:  julia --project=. experiments/tools/table_master_results.jl
# =============================================================================

include(joinpath(@__DIR__, "..", "scripts", "03_plots.jl"))   # helpers; main() guarded
using DataFrames, CSV
using Statistics
using Printf

const OUT = joinpath(_ROOT, "experiments", "out")

const PROB_TEX = Dict(
    :mvn => "MVN", :banana => "Banana", :funnel => "Funnel",
    :mridges => "M-ridges", :shell => "Shell",
    :mridges_spiky => "Spiky M-ridges", :eggbox => "Eggbox")
const ALG_TEX = Dict(
    :is => "IS", :mh => "MH", :nuts => "NUTS", :ns => "NS",
    :mw => "MoleWhacker")
const PROB_ORDER_TBL = Symbol[:mvn, :banana, :funnel, :mridges,
                              :shell, :mridges_spiky, :eggbox]
const ALG_ORDER_TBL  = Symbol[:is, :mh, :nuts, :ns, :mw]

_b_tex(B::Real) = B == 5e3 ? "5\\times 10^{3}" :
                  B == 5e4 ? "5\\times 10^{4}" :
                  B == 5e5 ? "5\\times 10^{5}" :
                  @sprintf("%g", B)

function _fmt(x::Real)
    isnan(x) && return "--"
    ax = abs(x)
    ax == 0 && return "0"
    if 0.01 <= ax < 1000
        return "\\(" * @sprintf("%.3g", x) * "\\)"
    end
    s = @sprintf("%.2e", x)
    m, e = split(s, 'e')
    mm = rstrip(rstrip(m, '0'), '.')
    ee = parse(Int, e)
    return "\\(" * mm * "\\times 10^{" * string(ee) * "}\\)"
end

function main()
    df = CSV.read(joinpath(OUT, "tables", "cells.csv"), DataFrame)
    drop_v5_excluded_rows!(df)
    lines = String[]
    push!(lines, "% Auto-generated by experiments/tools/table_master_results.jl")
    push!(lines, "% from experiments/out/tables/cells.csv -- do not edit by hand.")
    push!(lines, "\\begingroup")
    push!(lines, "\\scriptsize")
    push!(lines, "\\setlength{\\tabcolsep}{3.5pt}")
    push!(lines, "\\begin{longtable}{@{}l c r r r r r r r@{}}")
    push!(lines, "\\caption[Master results table.]{Master results table: " *
        "per-cell medians over the admissible seeds for every " *
        "(problem, dimension, budget, algorithm) cell of the benchmark " *
        "grid. Columns: admissible/total seeds; median cost efficiency " *
        "\\(\\eta = \\neff/\\Nlike\\); median marginal Wasserstein-1 " *
        "error \\(\\overline{W}_{1}\\); median sliced Wasserstein " *
        "distance; median absolute log-evidence error " *
        "\\(|\\Delta\\log\\evidence|\\) (evidence-aware algorithms " *
        "only); median absolute quantile error at the median and at " *
        "the \\(97.5\\,\\%\\) level (coordinate-averaged absolute " *
        "deviations in the parameter's own units, smaller is better, " *
        "\\cref{subsec:bench-coverage}; on the multimodal targets the " *
        "central level is ill-conditioned and the outer level is the " *
        "meaningful calibration number, " *
        "\\cref{sec:bench-results-calibration}); median mode-recovery " *
        "rate (multimodal targets only). " *
        "``--'' marks metrics that are undefined for the cell; " *
        "\\(0/n\\) rows carry the exclusion reason as a superscript " *
        "(\\textsuperscript{r}: all seeds failed the " *
        "\\(\\hat R < 1.05\\) gate; \\textsuperscript{i}: " *
        "budget-infeasible, the minimal honest run exceeds " *
        "\\(1.2\\,\\Nlike\\)).}\\label{tab:master-results}\\\\")
    header = "Algorithm & Seeds & \\(\\eta\\) & \\(\\overline{W}_{1}\\) & " *
             "SWD & \\(|\\Delta\\log\\evidence|\\) & " *
             "\\(\\mathrm{QE}(.5)\\) & \\(\\mathrm{QE}(.975)\\) & " *
             "Recovery \\\\"
    push!(lines, "\\toprule")
    push!(lines, header)
    push!(lines, "\\midrule")
    push!(lines, "\\endfirsthead")
    push!(lines, "\\multicolumn{9}{@{}l}{\\tablename\\ \\thetable{} (continued)}\\\\")
    push!(lines, "\\toprule")
    push!(lines, header)
    push!(lines, "\\midrule")
    push!(lines, "\\endhead")
    push!(lines, "\\midrule")
    push!(lines, "\\multicolumn{9}{r@{}}{\\emph{continued on next page}}\\\\")
    push!(lines, "\\endfoot")
    push!(lines, "\\bottomrule")
    push!(lines, "\\endlastfoot")

    for prob in PROB_ORDER_TBL
        sub_p = df[df.problem .== String(prob), :]
        for dd in sort(unique(sub_p.d))
            for BB in sort(unique(sub_p.B))
                push!(lines, "\\addlinespace[0.9ex]")
                push!(lines, "\\multicolumn{9}{@{}l}{\\textbf{" *
                    PROB_TEX[prob] * "}\\quad \\(d = " * string(Int(dd)) *
                    "\\), \\(\\Nlike = " * _b_tex(BB) * "\\)}\\\\*")
                push!(lines, "\\addlinespace[0.25ex]")
                for alg in ALG_ORDER_TBL
                    ss = sub_p[sub_p.algorithm .== String(alg) .&&
                               sub_p.d .== dd .&& sub_p.B .== BB, :]
                    n_tot = nrow(ss)
                    notes = [String(coalesce(n, "")) for n in ss.notes]
                    keep = [!(occursin("RHAT-FAIL", n) ||
                              occursin("BUDGET-VIOLATION", n) ||
                              occursin("budget-infeasible", n)) for n in notes]
                    n_adm = count(keep)
                    reason = ""
                    if n_adm == 0 && n_tot > 0
                        reason = any(occursin.("budget-infeasible", notes)) ?
                            "\\textsuperscript{i}" : "\\textsuperscript{r}"
                    end
                    med(col) = begin
                        v = filter(!isnan, Vector{Float64}(ss[keep, col]))
                        isempty(v) ? NaN : median(v)
                    end
                    eta  = med(:eta_Nlike)
                    w1   = med(:W1_marginal_avg)
                    swd  = med(:SWD)
                    dlz  = alg in (:mh, :nuts) ? NaN : begin
                        v = filter(!isnan, abs.(Vector{Float64}(ss[keep, :dlogZ])))
                        isempty(v) ? NaN : median(v)
                    end
                    qe50 = med(:QE_p500)
                    qe975 = med(:QE_p975)
                    rec  = med(:mode_recovery)
                    row = ALG_TEX[alg] * " & " *
                        string(n_adm) * "/" * string(n_tot) * reason * " & " *
                        _fmt(eta) * " & " * _fmt(w1) * " & " * _fmt(swd) *
                        " & " * _fmt(dlz) * " & " *
                        _fmt(qe50) * " & " * _fmt(qe975) * " & " *
                        (isnan(rec) ? "--" : "\\(" * @sprintf("%.2f", rec) * "\\)") *
                        " \\\\"
                    push!(lines, row)
                end
            end
        end
    end
    push!(lines, "\\end{longtable}")
    push!(lines, "\\endgroup")
    out_tex = joinpath(OUT, "tables", "master_results_table.tex")
    open(out_tex, "w") do io
        for l in lines
            println(io, l)
        end
    end
    @info "master results table written" out_tex n_lines = length(lines)
    return 0
end

if abspath(PROGRAM_FILE) == @__FILE__
    exit(main())
end
