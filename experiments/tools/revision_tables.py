import os, re
import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "experiments", "out")
REV = os.path.join(OUT, "revision_2026-09-25")
TAB = os.path.join(REV, "tables")
os.makedirs(TAB, exist_ok=True)

PROB_TEX = {"mvn": r"\mvn{}", "banana": r"\banana{}", "funnel": r"\funnel{}", "mridges": r"\mridges{}",
            "shell": r"\shell{}", "mridges_spiky": r"\mridgesspiky{}", "eggbox": r"\eggbox{}"}
PROB_ORDER = ["mvn", "banana", "funnel", "mridges", "shell", "mridges_spiky", "eggbox"]
ALG_TEX = {"is": r"\isamp{}", "mh": r"\mh{}", "nuts": r"\nuts{}", "ns": r"\ns{}", "mw": r"\mw{}"}
ALG_ORDER = ["is", "mh", "nuts", "ns", "mw"]
B_TEX = {5e3: r"5\times 10^{3}", 5e4: r"5\times 10^{4}", 5e5: r"5\times 10^{5}"}


def fmt(x, digits=3, sci_below=0.01):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    ax = abs(x)
    if ax == 0:
        return r"\(0\)"
    if sci_below <= ax < 1000:
        return r"\(" + f"{x:.{digits}g}" + r"\)"
    m, e = f"{x:.2e}".split("e")
    m = m.rstrip("0").rstrip(".")
    return r"\(" + m + r"\times 10^{" + str(int(e)) + r"}\)"


def med(v):
    v = np.asarray([x for x in v if x is not None and np.isfinite(x)], dtype=float)
    return float(np.median(v)) if v.size else float("nan")


def header(name, caption, label, colspec, head, ncols=None, tabcolsep="3pt"):
    if ncols is None:
        ncols = head.count("&") + 1
    return [f"% Auto-generated by experiments/tools/revision_tables.py ({name}); do not edit by hand.",
            r"\begingroup", r"\scriptsize", r"\setlength{\tabcolsep}{" + tabcolsep + "}",
            r"\begin{longtable}{" + colspec + "}",
            r"\caption[" + caption[0] + "]{" + caption[1] + r"}\label{" + label + r"}\\",
            r"\toprule", head, r"\midrule", r"\endfirsthead",
            r"\multicolumn{" + str(ncols) + r"}{@{}l}{\tablename\ \thetable{} (continued)}\\",
            r"\toprule", head, r"\midrule", r"\endhead", r"\midrule",
            r"\multicolumn{" + str(ncols) + r"}{r@{}}{\emph{continued on next page}}\\",
            r"\endfoot", r"\bottomrule", r"\endlastfoot"]


def write(lines, fname):
    lines = lines + [r"\end{longtable}", r"\endgroup"]
    with open(os.path.join(TAB, fname), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", fname, len(lines), "lines")


# -----------------------------------------------------------------------------
cells = pd.read_csv(os.path.join(OUT, "tables", "cells.csv"))
cells["notes"] = cells["notes"].fillna("")
fresh = pd.read_csv(os.path.join(REV, "cells_fresh.csv"))
part = pd.read_csv(os.path.join(REV, "partition_mass.csv")) if os.path.exists(os.path.join(REV, "partition_mass.csv")) else None


def admissible(row):
    n = row["notes"]
    return not ("RHAT-FAIL" in n or "BUDGET-VIOLATION" in n or "budget-infeasible" in n)


cells["adm"] = cells.apply(admissible, axis=1)

# ---- 1. fresh vs population -------------------------------------------------
cap = ("MoleWhacker: archived population against the frozen-mixture fresh draw.",
       r"\mw{} per (target, dimension, budget) cell: medians over all seeds of the archived accumulated-population "
       r"output (\emph{pop}: final-mixture weights, \(\effic\) per consumed cost \(\Nlike\)) and of the frozen-mixture "
       r"fresh-draw estimator (\emph{fresh}: \(N_{\mathrm{fresh}} = \lfloor B - \Nlike\rfloor\) independent draws from "
       r"the stored final mixture, weighted by the exact target; \(\effic^{\mathrm{fresh}} = \neff/(\Nlike + N_{\mathrm{fresh}})\) "
       r"per total charged cost, \(\efficis^{\mathrm{fresh}} = \neff/N_{\mathrm{fresh}}\) per fresh draw). "
       r"Seeds column: seeds with a fresh estimate / seeds whose archived cost already reached the budget (no fresh draw within budget) / all seeds. "
       r"The population efficiency \(\effic\) pop is the median over all archived seeds; the population and fresh accuracy columns are paired on the fresh-eligible seeds (so \funnel{} at \(d = 2\), \(\Nlike = 5\times 10^{4}\) uses \(19\) of \(20\) seeds there, and cells without a fresh estimate show no accuracy entry although archived values exist in \cref{tab:master-results}). "
       r"\(\hat k\): median Pareto shape of the fresh weights. \(\wonebar\) and \(|\Delta\log\evidence|\) use the archived truth sets and the fixed-\(10^{4}\) resampling convention of \cref{sec:bench-metrics}. "
       r"Tool: \texttt{experiments/tools/fresh\_draw\_recompute.jl}; per-run records in \texttt{experiments/out/revision\_2026-09-25/}.")
head = (r"& & & & & \multicolumn{3}{c}{efficiency} & & \multicolumn{2}{c}{\(\wonebar\)} & \multicolumn{2}{c}{\(|\Delta\log\evidence|\) [\(10^{-3}\)]} \\"
        r"\cmidrule(lr){6-8}\cmidrule(lr){10-11}\cmidrule(lr){12-13}"
        r"Target & \(d\) & \(\Nlike\) & Seeds & \(N_{\mathrm{fresh}}\) [k] & \(\effic\) pop & \(\effic^{\mathrm{fresh}}\) & "
        r"\(\efficis^{\mathrm{fresh}}\) & \(\hat k\) & pop & fresh & pop & fresh \\")
lines = header("fresh_vs_population", cap, "tab:fresh-vs-population", "@{}l c c c r r r r r r r r r@{}", head, ncols=13, tabcolsep="2.0pt")
for prob in PROB_ORDER:
    for d in sorted(fresh[fresh.problem == prob].d.unique()):
        for B in sorted(fresh[(fresh.problem == prob) & (fresh.d == d)].B.unique()):
            s = fresh[(fresh.problem == prob) & (fresh.d == d) & (fresh.B == B)]
            ok = s[s.status.isin(["full_remaining_budget", "capped_within_budget"]) & (s.weight_status == "ok")]
            nob = s[s.status.isin(["no_fresh_estimate_within_budget", "exceeds_strict_budget"])]
            row = " & ".join([
                PROB_TEX[prob], str(int(d)), r"\(" + B_TEX[B] + r"\)",
                f"{len(ok)}/{len(nob)}/{len(s)}",
                (r"\(" + f"{med(ok.N_fresh) / 1e3:.0f}" + r"\)") if len(ok) else "--",
                fmt(med(s.eta_pop_consumed), 2),
                fmt(med(ok.eta_cost_fresh), 2) if len(ok) else "--",
                fmt(med(ok.eta_proposal_fresh), 2) if len(ok) else "--",
                fmt(med(ok.pareto_k_fresh), 2) if len(ok) else "--",
                fmt(med(s.W1_marginal_avg_pop), 2) if "W1_marginal_avg_pop" in s else "--",
                fmt(med(ok.W1_marginal_avg_fresh), 2) if len(ok) else "--",
                (r"\(" + f"{1e3 * med(s.dlogZ_pop):.3g}" + r"\)") if "dlogZ_pop" in s and np.isfinite(med(s.dlogZ_pop)) else "--",
                (r"\(" + f"{1e3 * med(ok.dlogZ_fresh):.3g}" + r"\)") if len(ok) else "--",
            ]) + r" \\"
            lines.append(row)
write(lines, "fresh_vs_population.tex")

# ---- 2. pass fractions and all-returned medians (B10) ------------------------
cap = ("Admissible seeds by exclusion reason, with conditional and all-returned medians.",
       r"Per (target, dimension, budget, algorithm) cell: seeds admissible / total, and the excluded seeds by reason "
       r"(r: \(\rhat > 1.05\); b: cost outside the \([0.8, 1.2]\,\Nlike\) band; i: budget-infeasible, no output). "
       r"\(\wonebar\) and \(|\Delta\log\evidence|\) are given twice: the median over the admissible seeds (the "
       r"convention of every headline figure) and the median over all seeds that returned an output "
       r"(\emph{all}), which includes \(\rhat\) failures and budget violations but cannot include the "
       r"budget-infeasible cells, whose count is given. Cells with no admissible seed are still listed.")
head = (r"Target & \(d\) & \(\Nlike\) & Alg. & adm./total & r & b & i & \(\wonebar\) adm. & \(\wonebar\) all & "
        r"\(|\Delta\log\evidence|\) adm. & \(|\Delta\log\evidence|\) all \\")
lines = header("pass_fractions", cap, "tab:pass-fractions", "@{}l c c l c r r r r r r r@{}", head)
for prob in PROB_ORDER:
    sp = cells[cells.problem == prob]
    for d in sorted(sp.d.unique()):
        for B in sorted(sp[sp.d == d].B.unique()):
            for alg in ALG_ORDER:
                s = sp[(sp.d == d) & (sp.B == B) & (sp.algorithm == alg)]
                if s.empty:
                    continue
                r = int(s.notes.str.contains("RHAT-FAIL").sum())
                b = int(s.notes.str.contains("BUDGET-VIOLATION").sum())
                i = int(s.notes.str.contains("budget-infeasible").sum())
                adm = s[s.adm]
                ret = s[~s.notes.str.contains("budget-infeasible")]
                dz_adm = med(adm.dlogZ.abs()) if alg in ("is", "ns", "mw") else float("nan")
                dz_all = med(ret.dlogZ.abs()) if alg in ("is", "ns", "mw") else float("nan")
                lines.append(" & ".join([PROB_TEX[prob], str(int(d)), r"\(" + B_TEX[B] + r"\)", ALG_TEX[alg],
                                         f"{len(adm)}/{len(s)}", str(r), str(b), str(i),
                                         fmt(med(adm.W1_marginal_avg)), fmt(med(ret.W1_marginal_avg)),
                                         fmt(dz_adm), fmt(dz_all)]) + r" \\")
write(lines, "pass_fractions.tex")

# ---- 3. wall times -----------------------------------------------------------
cap = ("Measured wall time per cell.",
       r"Median wall-clock time in seconds over all seeds that returned an output, per (target, dimension, budget) "
       r"cell and algorithm, as recorded by the harness (\texttt{wall\_time\_s} in \texttt{cells.csv}; single "
       r"workstation, Julia 1.11, thread counts as in \cref{sec:bench-runsheet}). Wall time is reported next to the "
       r"derivative-weighted cost \(\Nlike\) and is not the basis of the efficiency \(\effic\). "
       r"\mw{} stops at its iteration cap and typically spends a fraction of the nominal budget "
       r"(\cref{tab:fresh-vs-population}); budget-infeasible cells carry no time.")
head = r"Target & \(d\) & \(\Nlike\) & " + " & ".join(ALG_TEX[a] for a in ALG_ORDER) + r" \\"
lines = header("wall_times", cap, "tab:wall-times", "@{}l c c r r r r r@{}", head)
for prob in PROB_ORDER:
    sp = cells[cells.problem == prob]
    for d in sorted(sp.d.unique()):
        for B in sorted(sp[sp.d == d].B.unique()):
            vals = []
            for alg in ALG_ORDER:
                s = sp[(sp.d == d) & (sp.B == B) & (sp.algorithm == alg) & ~sp.notes.str.contains("budget-infeasible")]
                vals.append(fmt(med(s.wall_time_s), 3) if len(s) else "--")
            lines.append(" & ".join([PROB_TEX[prob], str(int(d)), r"\(" + B_TEX[B] + r"\)"] + vals) + r" \\")
write(lines, "wall_times.tex")

# ---- 5. fresh headline (d = 5, eggbox d = 2, B = 5e5): two aligned panels ----
hl_eff, hl_acc = [], []
for prob in PROB_ORDER:
    d = 2 if prob == "eggbox" else 5
    s = fresh[(fresh.problem == prob) & (fresh.d == d) & (fresh.B == 5e5)]
    ok = s[(s.weight_status == "ok")]
    o = cells[(cells.problem == prob) & (cells.d == d) & (cells.B == 5e5) & (cells.algorithm != "mw") & cells.adm]
    eta_o = o.groupby("algorithm").eta_Nlike.median()
    w1_o = o.groupby("algorithm").W1_marginal_avg.median()
    dz_o = o[o.algorithm.isin(["is", "ns"])].groupby("algorithm").dlogZ.apply(lambda v: float(np.median(np.abs(v))))
    def best(series, mode, scale=1.0, digits=3):
        if series.empty:
            return "--"
        idx = series.idxmax() if mode == "max" else series.idxmin()
        return fmt(scale * series[idx], digits) + " " + ALG_TEX[idx]
    label = PROB_TEX[prob] + (r" (\(d = 2\))" if prob == "eggbox" else "")
    hl_eff.append(" & ".join([label, fmt(med(s.eta_pop_consumed)), fmt(med(ok.eta_cost_fresh)), fmt(med(ok.eta_proposal_fresh)),
                              fmt(med(ok.pareto_k_fresh), 2), best(eta_o, "max")]) + r" \\")
    hl_acc.append(" & ".join([label, fmt(med(s.W1_marginal_avg_pop)), fmt(med(ok.W1_marginal_avg_fresh)), best(w1_o, "min"),
                              fmt(1e3 * med(s.dlogZ_pop), 3, sci_below=0.001), fmt(1e3 * med(ok.dlogZ_fresh), 3, sci_below=0.001),
                              best(dz_o, "min", scale=1e3)]) + r" \\")
with open(os.path.join(TAB, "fresh_headline.tex"), "w", encoding="utf-8", newline="\n") as f:
    f.write("% Auto-generated by experiments/tools/revision_tables.py (fresh_headline); do not edit by hand.\n")
    f.write(r"\begin{tabular}{@{}l rrrr l@{}}" + "\n" + r"\toprule" + "\n")
    f.write(r"\multicolumn{6}{@{}l}{(a) Efficiency (Kish diagnostics)} \\" + "\n" + r"\midrule" + "\n")
    f.write(r"Target & \(\effic\) pop & \(\effic^{\mathrm{fresh}}\) & \(\efficis^{\mathrm{fresh}}\) & \(\hat k\) & best other \(\effic\) \\" + "\n" + r"\midrule" + "\n")
    f.write("\n".join(hl_eff) + "\n" + r"\bottomrule" + "\n" + r"\end{tabular}" + "\n\n" + r"\vspace{1.2ex}" + "\n\n")
    f.write(r"\begin{tabular}{@{}l rr l rr l@{}}" + "\n" + r"\toprule" + "\n")
    f.write(r"\multicolumn{7}{@{}l}{(b) Accuracy against the independent truth (lower is better)} \\" + "\n" + r"\midrule" + "\n")
    f.write(r"& \multicolumn{3}{c}{\(\wonebar\)} & \multicolumn{3}{c}{\(|\Delta\log\evidence|\) [\(10^{-3}\)]} \\" + "\n")
    f.write(r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}" + "\n")
    f.write(r"Target & pop & fresh & best other & pop & fresh & best other \\" + "\n" + r"\midrule" + "\n")
    f.write("\n".join(hl_acc) + "\n" + r"\bottomrule" + "\n" + r"\end{tabular}" + "\n")
print("wrote fresh_headline.tex (two panels)")

