# ---- 4. partition headline (TV at B = 5e5, d = 5) ----------------------------
if part is not None:
    rows = []
    for prob in ["mridges", "mridges_spiky"]:
        s = part[(part.problem == prob) & (part.d == 5) & (part.B == 5e5) & part.admissible]
        cellvals = {}
        for alg in ALG_ORDER:
            est = "population" if alg == "mw" else "output"
            v = s[(s.algorithm == alg) & (s.estimator == est)].TV_partition
            cellvals[alg] = (med(v), len(v))
        vf = s[(s.algorithm == "mw") & (s.estimator == "fresh")].TV_partition
        cellvals["mw_fresh"] = (med(vf), len(vf))
        rows.append((prob, cellvals))
    with open(os.path.join(TAB, "partition_headline.tex"), "w", encoding="utf-8", newline="\n") as f:
        f.write("% Auto-generated by experiments/tools/revision_tables.py (partition_headline); do not edit by hand.\n")
        f.write(r"\begin{tabular}{lrrrrrr}" + "\n" + r"\toprule" + "\n")
        f.write(r"Problem & \isamp{} & \mh{} & \nuts{} & \ns{} & MW pop. & MW fresh \\" + "\n" + r"\midrule" + "\n")
        for prob, cv in rows:
            def c(k):
                m, n = cv[k]
                return ("--" if not np.isfinite(m) else r"\(" + f"{m:.3f}" + r"\)") + (f" ({n})" if n else "")
            label = {"mridges": r"\mridges{} (\(32\) orthants)", "mridges_spiky": r"\mridgesspiky{} (\(7\) intervals)"}[prob]
            f.write(" & ".join([label, c("is"), c("mh"), c("nuts"), c("ns"), c("mw"), c("mw_fresh")]) + r" \\" + "\n")
        f.write(r"\bottomrule" + "\n" + r"\end{tabular}" + "\n")
    print("wrote partition_headline.tex")
