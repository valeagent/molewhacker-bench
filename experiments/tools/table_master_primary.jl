#!/usr/bin/env julia
# =============================================================================
# table_master_primary.jl — PRIMARY master results table (thesis Appendix B,
# tab:master-results), revision of 27 September 2026.
#
# Same longtable layout, columns, label and number formatting as
# table_master_results.jl, but read from the canonical primary view
# experiments/out/primary_fresh_2026-09-27/primary_cells.csv (built by
# primary_fresh_view.jl): MoleWhacker rows report the independent final
# sample drawn from the frozen mixture with the remaining budget, never the
# accumulated adaptation population. MW seed counts are n_eligible/n_total;
# a cell without any within-budget final sample carries the superscript
# "f" and "--" in every metric column. TV_part comes from
# partition_mass.csv with estimator == "fresh" for MW and "output" for the
# other algorithms. No sampling, no target evaluation.
#
# Usage:  julia --project=. experiments/tools/table_master_primary.jl
# Output: experiments/out/primary_fresh_2026-09-27/tables/B-master-table.tex
# =============================================================================

using DataFrames, CSV
using Statistics
using Printf

const _ROOT   = abspath(joinpath(@__DIR__, "..", ".."))
const OUT     = joinpath(_ROOT, "experiments", "out")
const PRIMARY = joinpath(OUT, "primary_fresh_2026-09-27")
const TABLES  = joinpath(PRIMARY, "tables")

const PROB_TEX = Dict(
    "mvn" => "MVN", "banana" => "Banana", "funnel" => "Funnel",
    "mridges" => "M-ridges", "shell" => "Shell",
    "mridges_spiky" => "Spiky M-ridges", "eggbox" => "Eggbox")
const ALG_TEX = Dict(
    "is" => "IS", "mh" => "MH", "nuts" => "NUTS", "ns" => "NS",
    "mw" => "MoleWhacker")
const PROB_ORDER_TBL = ["mvn", "banana", "funnel", "mridges", "shell", "mridges_spiky", "eggbox"]
const ALG_ORDER_TBL  = ["is", "mh", "nuts", "ns", "mw"]

_b_tex(B::Real) = B == 5e3 ? "5\\times 10^{3}" :
                  B == 5e4 ? "5\\times 10^{4}" :
                  B == 5e5 ? "5\\times 10^{5}" :
                  @sprintf("%g", B)

function _fmt(x::Real)
    isnan(x) && return "--"
    ax = abs(x)
    ax == 0 && return "0"
    if 0.01 <= ax < 1000
        return "\\(" * @sprintf("%.3g", x) * "\\)"
    end
    s = @sprintf("%.2e", x)
    m, e = split(s, 'e')
    mm = rstrip(rstrip(m, '0'), '.')
    ee = parse(Int, e)
    return "\\(" * mm * "\\times 10^{" * string(ee) * "}\\)"
end

_str(x) = x === missing ? "" : String(string(x))
_admissible(note::AbstractString) = !(occursin("RHAT-FAIL", note) || occursin("BUDGET-VIOLATION", note) ||
                                      occursin("budget-infeasible", note))

function main()
    isdir(TABLES) || mkpath(TABLES)
    df = CSV.read(joinpath(PRIMARY, "primary_cells.csv"), DataFrame)
    df.notes = [_str(x) for x in df.notes]
    df.eligibility_status = [_str(x) for x in df.eligibility_status]
    part_path = joinpath(OUT, "revision_2026-09-25", "partition_mass.csv")
    part = isfile(part_path) ? CSV.read(part_path, DataFrame) : nothing
    part === nothing && @warn "partition_mass.csv not found; TV_part column will be empty" part_path
    if part !== nothing
        part.admissible = [x === missing ? false : (x isa Bool ? x : lowercase(String(x)) == "true") for x in part.admissible]
    end

    # Availability counts quoted in the caption are taken from the data.
    mw = df[df.algorithm .== "mw", :]
    n_mw_total = nrow(mw)
    n_mw_elig  = count(mw.eligibility_status .== "eligible")
    mw_cells   = combine(groupby(mw, [:problem, :d, :B]), :eligibility_status => (v -> count(==("eligible"), v)) => :n_e)
    n_cells_total = nrow(mw_cells)
    n_cells_elig  = count(mw_cells.n_e .> 0)
    ctot_eq_B = all(r -> r.eligibility_status != "eligible" || (r.C_total == r.B), eachrow(mw))
    cost_clause = ctot_eq_B ?
        "which equals the nominal budget \\(\\Nlike\\) for every available run" :
        "which is at most the nominal budget \\(\\Nlike\\)"

    lines = String[]
    push!(lines, "% Auto-generated by experiments/tools/table_master_primary.jl")
    push!(lines, "% from experiments/out/primary_fresh_2026-09-27/primary_cells.csv -- do not edit by hand.")
    push!(lines, "\\begingroup")
    push!(lines, "\\scriptsize")
    push!(lines, "\\setlength{\\tabcolsep}{2.8pt}")
    push!(lines, "\\begin{longtable}{@{}l c r r r r r r r@{}}")
    push!(lines, "\\caption[Master results table.]{Master results table: " *
        "per-cell medians for every (problem, dimension, budget, algorithm) cell " *
        "of the benchmark grid. \\mw{} values are computed from the independent " *
        "final sample drawn from the frozen final mixture with the remaining " *
        "budget (\\(M\\) weighted draws), charged at the total cost " *
        "\\(C_{\\mathrm{total}} = C_{\\mathrm{adapt}} + M\\), " * cost_clause * "; " *
        "\\(" * string(n_mw_elig) * "\\) of the \\(" * string(n_mw_total) * "\\) \\mw{} runs " *
        "(\\(" * string(n_cells_elig) * "\\) of the \\(" * string(n_cells_total) * "\\) " *
        "(problem, dimension, budget) combinations) have a within-budget final estimate. " *
        "Columns: available/total seeds (for \\mw{}: seeds with a final estimate; for the other " *
        "algorithms: admissible seeds); median cost-efficiency " *
        "\\(\\effic = \\neff/\\Nlike\\) (for \\mw{}: Kish \\(\\neff\\) of the final sample per unit of " *
        "\\(C_{\\mathrm{total}}\\)); median marginal Wasserstein-1 error \\(\\wonebar\\); median sliced Wasserstein " *
        "distance; median absolute log-evidence error " *
        "\\(|\\Delta\\log\\evidence|\\) (evidence-aware algorithms " *
        "only; for \\mw{} the ordinary importance-sampling evidence of the final sample); " *
        "median absolute quantile error at the median and at " *
        "the \\(97.5\\,\\%\\) level (coordinate-averaged absolute " *
        "deviations in the parameter's own units, smaller is better, " *
        "\\cref{subsec:bench-coverage}; on the smooth \\mridges{} cells the " *
        "central level is ill-conditioned, because the true median of each " *
        "bimodal coordinate falls in the valley between two symmetric modes, " *
        "and the outer level is the meaningful calibration number there, " *
        "\\cref{sec:bench-results-calibration}); median partition-mass " *
        "error \\(\\mathrm{TV}_{\\mathrm{part}}\\) " *
        "(\\mridges{} and \\mridgesspiky{} only, \\cref{subsec:bench-recovery}; for \\mw{} " *
        "computed from the native weights of the final sample, for the other algorithms " *
        "from the reported output; per-seed values in " *
        "\\texttt{experiments/out/revision\\_2026-09-25/partition\\_mass.csv} " *
        "of the companion repository, estimator \\texttt{fresh} and \\texttt{output}). " *
        "``--'' marks metrics that are undefined for the cell or cells without an available run; " *
        "\\(0/n\\) rows carry the exclusion reason as a superscript " *
        "(\\textsuperscript{r}: all seeds failed the " *
        "\\(\\rhat < 1.05\\) gate; \\textsuperscript{b}: all seeds " *
        "violated the budget band; \\textsuperscript{i}: " *
        "budget-infeasible, the minimal complete run exceeds " *
        "\\(1.2\\,\\Nlike\\); \\textsuperscript{f}: no within-budget final sample, " *
        "the adaptation alone consumed the budget; combinations are listed).}\\label{tab:master-results}\\\\")
    header = "Algorithm & Seeds & \\(\\effic\\) & \\(\\wonebar\\) & " *
             "SWD & \\(|\\Delta\\log\\evidence|\\) & " *
             "\\(\\mathrm{QE}(.5)\\) & \\(\\mathrm{QE}(.975)\\) & " *
             "\\(\\mathrm{TV}_{\\mathrm{part}}\\) \\\\"
    push!(lines, "\\toprule")
    push!(lines, header)
    push!(lines, "\\midrule")
    push!(lines, "\\endfirsthead")
    push!(lines, "\\multicolumn{9}{@{}l}{\\tablename\\ \\thetable{} (continued)}\\\\")
    push!(lines, "\\toprule")
    push!(lines, header)
    push!(lines, "\\midrule")
    push!(lines, "\\endhead")
    push!(lines, "\\midrule")
    push!(lines, "\\multicolumn{9}{r@{}}{\\emph{continued on next page}}\\\\")
    push!(lines, "\\endfoot")
    push!(lines, "\\bottomrule")
    push!(lines, "\\endlastfoot")

    n_rows = 0; n_mw_rows_f = 0
    for prob in PROB_ORDER_TBL
        sub_p = df[df.problem .== prob, :]
        for dd in sort(unique(sub_p.d))
            for BB in sort(unique(sub_p.B))
                push!(lines, "\\addlinespace[0.9ex]")
                push!(lines, "\\multicolumn{9}{@{}l}{\\textbf{" *
                    PROB_TEX[prob] * "}\\quad \\(d = " * string(Int(dd)) *
                    "\\), \\(\\Nlike = " * _b_tex(BB) * "\\)}\\\\*")
                push!(lines, "\\addlinespace[0.25ex]")
                for alg in ALG_ORDER_TBL
                    ss = sub_p[(sub_p.algorithm .== alg) .& (sub_p.d .== dd) .& (sub_p.B .== BB), :]
                    n_tot = nrow(ss)
                    notes = ss.notes
                    keep = alg == "mw" ? (ss.eligibility_status .== "eligible") :
                                         [_admissible(n) for n in notes]
                    n_adm = count(keep)
                    reason = ""
                    if n_adm == 0 && n_tot > 0
                        causes = String[]
                        if alg == "mw"
                            push!(causes, "f"); n_mw_rows_f += 1
                        else
                            any(occursin.("RHAT-FAIL", notes)) && push!(causes, "r")
                            any(occursin.("BUDGET-VIOLATION", notes)) && push!(causes, "b")
                            any(occursin.("budget-infeasible", notes)) && push!(causes, "i")
                            isempty(causes) && push!(causes, "?")
                        end
                        reason = "\\textsuperscript{" * join(causes, ",") * "}"
                    end
                    med(col) = begin
                        v = filter(!isnan, Vector{Float64}(ss[keep, col]))
                        isempty(v) ? NaN : median(v)
                    end
                    eta  = med(:eta_Nlike)
                    w1   = med(:W1_marginal_avg)
                    swd  = med(:SWD)
                    dlz  = alg in ("mh", "nuts") ? NaN : begin
                        v = filter(!isnan, abs.(Vector{Float64}(ss[keep, :dlogZ])))
                        isempty(v) ? NaN : median(v)
                    end
                    qe50 = med(:QE_p500)
                    qe975 = med(:QE_p975)
                    rec = NaN
                    if part !== nothing
                        est = alg == "mw" ? "fresh" : "output"
                        pp = part[(part.problem .== prob) .& (part.algorithm .== alg) .&
                                  (part.d .== dd) .& (part.B .== BB) .& part.admissible .&
                                  (part.estimator .== est), :]
                        v = filter(!isnan, Vector{Float64}(pp.TV_partition))
                        rec = isempty(v) ? NaN : median(v)
                    end
                    row = ALG_TEX[alg] * " & " *
                        string(n_adm) * "/" * string(n_tot) * reason * " & " *
                        _fmt(eta) * " & " * _fmt(w1) * " & " * _fmt(swd) *
                        " & " * _fmt(dlz) * " & " *
                        _fmt(qe50) * " & " * _fmt(qe975) * " & " *
                        _fmt(rec) *
                        " \\\\"
                    push!(lines, row)
                    n_rows += 1
                end
            end
        end
    end
    push!(lines, "\\end{longtable}")
    push!(lines, "\\endgroup")
    out_tex = joinpath(TABLES, "B-master-table.tex")
    open(out_tex, "w") do io
        for l in lines
            println(io, l)
        end
    end
    @info "primary master results table written" out_tex n_lines = length(lines) n_algorithm_rows = n_rows n_mw_rows_without_final_sample = n_mw_rows_f n_mw_eligible = n_mw_elig n_cells_eligible = n_cells_elig
    return 0
end

if abspath(PROGRAM_FILE) == @__FILE__
    exit(main())
end
